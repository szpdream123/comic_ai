## 八、场景、人物、道具的忠实性约束

（本节为“改编铁律”第10条视觉实体绝对忠实的执行细则）

### 场景约束
1. 场景只能来自原文，不得新增。若原文无过渡空间描写，直接切镜头。
2. 环境细节必须有出处或合理推断。**推断范围收束**：原文写了A（如阴凉），只可补充A的感官可证实表现（如寒气、阴影的移动），不可创造新物理属性（如从阴凉跳到潮湿、霉味）。**排他条款**：若推断产生歧义（如“老旧”可推断灰尘也可推断霉味），只选视觉/听觉/触觉等可实证的，不选嗅觉/味觉等强主观感受。若原文未提供足够线索，宁可留白，不填补。
3. 首次出现的场景标注原文依据。

### 人物约束
1. 不得新增任何角色（包括路人），除非原文明确描写。
2. 未说话的角色只能用表情、眼神、动作反应，且反应符合原文状态和人物当前成长阶段。
3. 人物视觉特征必须有原文依据，原文未写的特征不发明。
4. 人物的行为反应必须符合其在人物弧光表中的当前阶段。

### 道具约束
1. 每一个被镜头关注的道具都必须在原文中出现。
2. 道具状态不发明（“一把铜钥匙”不能变成“磨得发亮的铜钥匙”）。
3. 道具归属必须延续，除非原文中发生了转移。


## 九、冲突与爽点设计原则（内部柔性指导）

1. **爽点需要铺垫**，但不强制“1-2场压抑一场释放”。允许在单场戏中通过微小反转实现轻爽点。
2. **爽点可以复杂**：胜利中夹杂代价，释放中藏着隐痛。
3. **冲突不必总是言语交锋**。一个停顿、一次视线回避、一个道具的摆放，都可以承载冲突。
4. **连续多场无明显冲突时**，检查是否可以通过：①用眼神或停顿暗示矛盾；②用道具位置变化暗示权力转移；③用对白节奏变化（突然沉默、打断）制造张力。但不要为了冲突而冲突，日常戏中鲜活的人物性格同样是看点。


