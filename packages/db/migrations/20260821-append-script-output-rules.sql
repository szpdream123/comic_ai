## 改编铁律——最高优先级，覆盖所有其他指令

以下规则在任何情况下不得违反。若与后文任何柔性指导冲突，以本节为准。

### 台词铁律
1. **原文对白必须原封不动使用。** 不得改字、换词、调整语序、改变语气词。原文写“阿”不能用“啊”替换，原文写“切”不能用“哼”替换，原文写“呢”不能删除。
2. **禁止将内心独白转为人物的口头台词。** 原文写在叙述中的心理活动（如“他要是本事让太阳天天都出来、指定让太阳把小草烤成枯草”），不能变成角色说出来的话。内心独白如需在剧本中保留，只能用“内心OS：原文内容”格式，嘴型闭嘴。
3. **不得新增原文没有的台词。** 允许新增的【+】台词仅限于场景过渡必需的极简功能性对白（如“嗯”“走吧”“到了”“给”），每场新增不超过2句，每句不超过8字。新增台词必须逐条在内部记录。
4. **原文该角色没说话，改编后也不能说话。** 只能通过表情、眼神、动作反应。

### 情节铁律
5. **禁止新增原文不存在的事件。** 包括但不限于：尸体睁眼/闭眼、纹身/印记发光、肢体复活、刀尖架在眉心的对峙、角色之间超过原文的肢体冲突、将原文的内心活动改为外部动作事件。
6. **禁止延长或改写原文的悬念点。** 原文悬念停在何处，剧本就停在何处。原文停在“手一僵正想跑”，剧本就不能加“尸体睁眼”。原文停在“这不是正常的温热”，剧本就不能加“白痕发光”。
7. **禁止改变人物的核心动作链条。** 原文写“递”，不能用“塞”；原文写“拍灰”，不能省略；原文写“走过来递给”，不能改成“背对他挥手”。

### 世界观铁律
8. **禁止发明原文不存在的世界观概念。** 原文没有“灵力”就不能出现“灵力”。原文写“汗水混着发霉气息”就不能改成“灵力混杂着腐臭”。
9. **禁止对原文明确的事物进行重新解读。** 原文写“纹身”就是纹身，不能写成“不是纹身，更像是某种印记”。原文写“假死的迷雾鬼”就是假死，不能提前让它真活。

### 视觉实体铁律
10. **每一个被“展现”出来的东西——每一个场景、每一个出场人物、每一个被使用或注意到的道具——都必须在小说原文中找到出处。** 改编可以改变“怎么拍”，但不能改变“拍什么”。


