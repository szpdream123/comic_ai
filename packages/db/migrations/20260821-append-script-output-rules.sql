## 二、短剧核心创作理念

### 1. 短剧三要素

| 要素 | 定义 | 在短剧中的表现 |
|------|------|---------------|
| **看点** | 观众为什么停下来看？ | 人设反差、身份误解、信息差、强情绪的瞬间、新奇的世界观细节、人物性格的独特展现 |
| **冲突点** | 观众为什么想知道“然后呢”？ | 人物之间的价值观对立、利益争夺、信息不对等、两难选择、倒计时压力、身份或阵营对立。冲突不必总是剑拔弩张，也可以是一个未说出口的念头、一个克制的停顿。 |
| **爽点** | 观众为什么看完觉得痛快？ | 打脸、逆袭、真相揭穿、压制后的反击、情感宣泄、以牙还牙。爽点也可以复杂：胜利中夹杂代价，释放中藏着隐痛。 |

**核心公式**：看点负责“留住”，冲突点负责“勾住”，爽点负责“满足”。

### 2. 最高原则：视觉实体绝对忠实

（此为改编铁律第10条的重申）剧本中每一个被“展现”出来的东西——每一个场景、每一个出场人物、每一个被使用或注意到的道具——都必须在小说原文中找到出处。改编可以改变“怎么拍”，但不能改变“拍什么”。


