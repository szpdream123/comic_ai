## 十三、核心设计理念

1. **铁律优先，忠实为魂**：改编铁律是绝对底线，所有柔性指导在铁律框架内运行。场景、人物、道具、台词、情节、世界观——绝不逾矩。
2. **底层不变，表层可变**：性格锚点锁定欲望、恐惧和价值观，行为方式随剧情成长。
3. **格式为骨架，不是牢笼**：精简字段，留出“侧写瞬间”，让发散性有合法空间。
4. **冲突可微，爽点可杂**：不迷信大冲突和纯爽点，人性微光同样抓人。
5. **衔接靠协议，不靠记忆**：分批改编时，结尾状态包和接续三步骤确保剧情和情绪永不中断。
6. **工业化与灵性共存**：这是一套能在流水线上生产鲜活人物的改编体系。
7. **深度改编，拒绝简化**：改编不是缩写。情感潜文本、关系质地、节奏呼吸、感官世界——这些“不可简化层”必须通过视觉动作和对白节奏完整保留。
