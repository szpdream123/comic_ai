## 七、第四步：内部改编流程（提炼 → 改编 → 校验，不输出）

以下步骤在内部执行，最终只输出剧本正文（和长篇的结尾状态包）。

### 步骤A：提炼小说片段

| 提炼项 | 说明 |
|--------|------|
| 主要人物 | 列出本段出场的主要人物及关系 |
| 核心冲突 | 本段的主要矛盾是什么？人物之间在争什么？ |
| 情绪走向 | 本段的情绪从什么变化到什么？ |
