| 可压缩或合并的内容 | 哪些可以精简？ |
| 关键场景 | 本段发生在哪几个主要空间？必须来自原文 |
| 关键道具 | 本段有哪些重要物品？必须来自原文 |
| 适合短剧的爆点/钩子 | 最吸引人的瞬间是什么？ |
| 人物反应是否符合当前成长阶段 | 根据人物弧光表，本段人物的行为应处于哪个阶段？ |

**冲突挖掘专项**（内部执行）：
1. 扫描人物关系中的冲突类型：价值观对立/权力压制/信息不对等/利益争夺/情感单向/身份误解。
2. 评估每个场景的冲突潜力：谁想要什么？谁在阻止他？在场的人谁和谁有矛盾？日常戏中，冲突可以是一个眼神、一个停顿、一个未说出口的念头。
   **示例**：一场三人晚饭戏。表面在聊天气，实际是母亲和女儿在争夺家庭话语权，冲突藏在谁给父亲夹菜的动作里，藏在女儿被截断的半句话里。
3. 提炼台词的潜台词：表面台词背后的真实意图是什么？

**深度改编提醒**（内部执行）：提炼不是缩写。你需要识别原文中以下“不可简化”的深度层——
- **情感潜文本**：人物说A，实际表达的是B。剧本中保留A，但通过动作和节奏让B可见。
- **关系质地**：两个人物之间的权力距离、亲密距离、谁在主动谁在退让——这些是改编的核心材料，不能简化成“两人对话”。
- **节奏呼吸**：原文的停顿、空白、重复，可能有结构性意义。不要自动压缩“无对话段落”。
- **感官世界**：原文的声音、光线、温度、质地——即使不是情节必须，也是世界构建的必须。

**冲突与爽点来源约束**：所有冲突和爽点都必须来自原文，只能放大，不能发明。**放大与发明的界限**：放大＝对原文已有动作/对白增加强度（如“看了一眼”→“目光紧盯”）。发明＝加入原文不存在的对抗性动作或台词（如原文无眼神描写，改为“怒目而视”）。原文无外部冲突时，只能用节奏变化暗示，不发明新的对抗行为。

