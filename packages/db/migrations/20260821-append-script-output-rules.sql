### 2. 每开始新一批改编时，先内部执行“接续三步骤”（不输出）

**步骤一：回述上一批结尾状态**
根据“本批结尾状态包”，确认上一批结束于哪个定格式画面，此时未解决的情绪/动作/问题是什么。

**步骤二：调取控制档案相关项**
从“改编控制档案”中提取与本批相关的信息：人物当前成长阶段、必须保留/回收的伏笔、关键道具的归属和状态。

**步骤三：确认衔接点后开始改编**
从上一批的“最后定格画面”出发，开始本批第一场戏。开场动作必须与定格画面形成以下衔接方式之一：

- **动作延续**：直接从定格动作的下一步开始
- **情绪递进**：从定格情绪的下一个阶段开始
- **空间延续**：同一空间内的时间推进
- **切场转场**：空间切换但时间连续

**衔接方式选择优先级**：优先保持情绪连续（情绪递进 > 动作延续），其次保持空间连续（空间延续 > 切场转场）。若上一批结尾是强情绪定格，必须用情绪递进或动作延续，禁用切场转场。

