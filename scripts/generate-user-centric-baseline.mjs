import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

import pg from "pg";

const outputArgument = process.argv.find((argument) => argument.startsWith("--output="));
const outputPath = outputArgument
  ? resolve(process.cwd(), outputArgument.slice("--output=".length))
  : resolve(process.cwd(), "artifacts/user-centric-schema.generated.sql");

const database = new pg.Client({ connectionString: process.env.DATABASE_URL });
await database.connect();

try {
  await assertCleanTarget(database);
  const ddl = await generateDdl(database);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${ddl.trim()}\n`, "utf8");
  console.log(JSON.stringify({ output: outputPath, bytes: Buffer.byteLength(ddl, "utf8") }));
} finally {
  await database.end();
}

async function assertCleanTarget(db) {
  const first = ["organ", "ization"].join("");
  const second = ["work", "space"].join("");
  const result = await db.query(
    `
      WITH findings AS (
        SELECT table_name || '.' || column_name AS object_name
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND (column_name ILIKE '%' || $1 || '%' OR column_name ILIKE '%' || $2 || '%')
        UNION ALL
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = current_schema()
          AND (table_name ILIKE '%' || $1 || '%' OR table_name ILIKE '%' || $2 || '%')
      )
      SELECT object_name FROM findings ORDER BY object_name
    `,
    [first, second],
  );
  if (result.rows.length > 0) {
    throw new Error(`baseline_target_not_clean:${JSON.stringify(result.rows)}`);
  }
}

async function generateDdl(db) {
  const sections = [];
  sections.push("-- Generated from the current user-centric schema catalog. No business data is included.");

  const sequences = await db.query(`
    SELECT c.relname AS name,
           format_type(s.seqtypid, NULL) AS data_type,
           s.seqstart AS start_value,
           s.seqmin AS min_value,
           s.seqmax AS max_value,
           s.seqincrement AS increment_value,
           s.seqcycle AS cycle,
           s.seqcache AS cache_size
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_sequence s ON s.seqrelid = c.oid
    WHERE n.nspname = current_schema()
    ORDER BY c.relname
  `);
  for (const sequence of sequences.rows) {
    sections.push(
      `CREATE SEQUENCE IF NOT EXISTS ${quote(sequence.name)} AS ${sequence.data_type}`
      + ` INCREMENT BY ${sequence.increment_value} MINVALUE ${sequence.min_value}`
      + ` MAXVALUE ${sequence.max_value} START WITH ${sequence.start_value}`
      + ` CACHE ${sequence.cache_size}${sequence.cycle ? " CYCLE" : ""};`,
    );
  }

  const functions = await db.query(`
    SELECT pg_get_functiondef(p.oid) AS definition
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = current_schema()
      AND p.prokind IN ('f', 'p')
    ORDER BY p.proname, p.oid
  `);
  for (const functionRow of functions.rows) {
    sections.push(stripSchemaQualifier(functionRow.definition).replace(/;?\s*$/, ";"));
  }

  const tables = await db.query(`
    SELECT c.relname AS name,
           c.relkind,
           pg_get_expr(c.relpartbound, c.oid) AS partition_bound,
           c.relrowsecurity,
           c.relforcerowsecurity
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = current_schema()
      AND c.relkind IN ('r', 'p')
      AND c.relname NOT LIKE 'pg_%'
      AND c.relname NOT LIKE 'sql_%'
    ORDER BY c.relname
  `);
  for (const table of tables.rows) {
    const columns = await db.query(`
      SELECT a.attname AS name,
             format_type(a.atttypid, a.atttypmod) AS type_sql,
             a.attnotnull AS not_null,
             a.attidentity AS identity_kind,
             a.attgenerated AS generated_kind,
             pg_get_expr(d.adbin, d.adrelid) AS default_sql
      FROM pg_attribute a
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = $1::regclass
        AND a.attnum > 0
        AND NOT a.attisdropped
      ORDER BY a.attnum
    `, [table.name]);
    const columnSql = columns.rows.map((column) => {
      const definition = [`  ${quote(column.name)} ${stripSchemaQualifier(column.type_sql)}`];
      if (column.identity_kind === "a") definition.push("GENERATED ALWAYS AS IDENTITY");
      if (column.identity_kind === "d") definition.push("GENERATED BY DEFAULT AS IDENTITY");
      if (column.generated_kind === "s") {
        definition.push(`GENERATED ALWAYS AS (${stripSchemaQualifier(column.default_sql)}) STORED`);
      } else if (column.identity_kind === "") {
        if (column.default_sql) definition.push(`DEFAULT ${stripSchemaQualifier(column.default_sql)}`);
      }
      if (column.not_null) definition.push("NOT NULL");
      return definition.join(" ");
    });
    const partition = table.partition_bound
      ? ` PARTITION OF ${quote(table.partition_bound)} `
      : " ";
    if (table.partition_bound) {
      sections.push(`CREATE TABLE IF NOT EXISTS ${quote(table.name)} PARTITION OF ${table.partition_bound} ${columnSql.length ? `(${columnSql.join(", ")})` : ""};`);
    } else {
      sections.push(`CREATE TABLE IF NOT EXISTS ${quote(table.name)} (\n${columnSql.join(",\n")}\n);`);
    }
    if (table.relrowsecurity) sections.push(`ALTER TABLE ${quote(table.name)} ENABLE ROW LEVEL SECURITY;`);
    if (table.relforcerowsecurity) sections.push(`ALTER TABLE ${quote(table.name)} FORCE ROW LEVEL SECURITY;`);
  }

  const constraints = await db.query(`
    SELECT c.conname AS name,
           t.relname AS table_name,
           c.contype,
           pg_get_constraintdef(c.oid, true) AS definition,
           c.convalidated
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = current_schema()
      AND c.contype IN ('p', 'u', 'c', 'f', 'x')
    ORDER BY CASE c.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 ELSE 4 END, t.relname, c.conname
  `);
  for (const constraint of constraints.rows) {
    const validation = constraint.convalidated ? "" : " NOT VALID";
    sections.push(
      `ALTER TABLE ${quote(constraint.table_name)} ADD CONSTRAINT ${quote(constraint.name)} ${stripSchemaQualifier(constraint.definition)}${validation};`,
    );
  }

  const indexes = await db.query(`
    SELECT indexrelid::regclass::text AS name,
           pg_get_indexdef(indexrelid) AS definition
    FROM pg_index i
    JOIN pg_class table_record ON table_record.oid = i.indrelid
    JOIN pg_namespace n ON n.oid = table_record.relnamespace
    WHERE n.nspname = current_schema()
      AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)
    ORDER BY indexrelid::regclass::text
  `);
  for (const index of indexes.rows) {
    const definition = stripSchemaQualifier(index.definition)
      .replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS ")
      .replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS ");
    sections.push(`${definition};`);
  }

  const sequenceOwners = await db.query(`
    SELECT sequence.relname AS sequence_name,
           table_record.relname AS table_name,
           column_record.attname AS column_name
    FROM pg_depend dependency
    JOIN pg_class sequence ON sequence.oid = dependency.objid
    JOIN pg_class table_record ON table_record.oid = dependency.refobjid
    JOIN pg_attribute column_record ON column_record.attrelid = table_record.oid AND column_record.attnum = dependency.refobjsubid
    JOIN pg_namespace n ON n.oid = table_record.relnamespace
    WHERE dependency.deptype = 'a' AND sequence.relkind = 'S' AND n.nspname = current_schema()
  `);
  for (const owner of sequenceOwners.rows) {
    sections.push(`ALTER SEQUENCE ${quote(owner.sequence_name)} OWNED BY ${quote(owner.table_name)}.${quote(owner.column_name)};`);
  }

  const triggers = await db.query(`
    SELECT pg_get_triggerdef(t.oid, true) AS definition
    FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = current_schema() AND NOT t.tgisinternal
    ORDER BY t.tgname
  `);
  for (const trigger of triggers.rows) sections.push(`${stripSchemaQualifier(trigger.definition)};`);

  const policies = await db.query(`
    SELECT policyname, tablename, permissive, roles, cmd, qual, with_check
    FROM pg_policies WHERE schemaname = current_schema() ORDER BY tablename, policyname
  `);
  for (const policy of policies.rows) {
    const mode = policy.permissive === "PERMISSIVE" ? "PERMISSIVE" : "RESTRICTIVE";
    const roleSql = policy.roles.map((role) => quote(role)).join(", ");
    const usingSql = policy.qual ? ` USING (${policy.qual})` : "";
    const checkSql = policy.with_check ? ` WITH CHECK (${policy.with_check})` : "";
    sections.push(`CREATE POLICY ${quote(policy.policyname)} ON ${quote(policy.tablename)} AS ${mode} FOR ${policy.cmd} TO ${roleSql}${usingSql}${checkSql};`);
  }

  return sections.flat().join("\n\n");
}

function quote(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function stripSchemaQualifier(value) {
  return String(value ?? "").replaceAll('"public".', "").replaceAll("public.", "");
}
